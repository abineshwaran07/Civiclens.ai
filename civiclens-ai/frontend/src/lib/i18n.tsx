interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key) => string;
  statusLabel: (s: Status) => string;
  priorityLabel: (p: Priority) => string;
  categoryLabel: (c: string) => string;
}

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem("civiclens_lang") === "ta" ? "ta" : "en"));
  useEffect(() => {
    localStorage.setItem("civiclens_lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<I18n>(
    () => ({
      lang,
      setLang: setLangState,
      t: (key) => dict[lang][key],
      statusLabel: (s) => STATUS[lang][s] ?? s,
      priorityLabel: (p) => PRIORITY[lang][p] ?? p,
      categoryLabel: (c) => (lang === "ta" ? CATEGORY_TA[c] ?? c : c),
    }),
    [lang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n must be used inside I18nProvider");
  return v;
}

